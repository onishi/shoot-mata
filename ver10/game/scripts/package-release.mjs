import { createHash } from "node:crypto";
import { cp, mkdir, readFile, readdir, rm, stat, writeFile } from "node:fs/promises";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const gameRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const distRoot = resolve(gameRoot, "dist");
const releaseRoot = resolve(gameRoot, "..", "release", "signal-garden-v10.0");

const guide = `SIGNAL GARDEN v10.0\n\nServe this directory with a static web server, then open it in Google Chrome.\n\nControls\n- Enter: start, continue, or resume\n- Left/Right or A/D: select a branch\n- Space: switch the selected branch; hold it in Garden 6\n- Escape: pause or resume\n- R: retry the current garden\n- M: cycle sound volume\n- V: toggle reduced motion\n\nProgress and preferences are stored locally in the browser. All visuals and audio are generated by the game code; no third-party media is included.\n`;

async function filesIn(directory) {
  const files = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = resolve(directory, entry.name);
    if (entry.isDirectory()) files.push(...await filesIn(path));
    else files.push(path);
  }
  return files;
}

await readFile(resolve(distRoot, "index.html"), "utf8");
await rm(releaseRoot, { recursive: true, force: true });
await mkdir(releaseRoot, { recursive: true });
await cp(distRoot, releaseRoot, { recursive: true });
await writeFile(resolve(releaseRoot, "README.txt"), guide, "utf8");

const manifestLines = [];
for (const path of (await filesIn(releaseRoot)).sort()) {
  const data = await readFile(path);
  const hash = createHash("sha256").update(data).digest("hex");
  manifestLines.push(`${hash}  ${relative(releaseRoot, path)}`);
}
await writeFile(resolve(releaseRoot, "SHA256SUMS.txt"), `${manifestLines.join("\n")}\n`, "utf8");

const bytes = (await Promise.all((await filesIn(releaseRoot)).map(async (path) => (await stat(path)).size))).reduce((sum, size) => sum + size, 0);
console.log(`Packaged ${releaseRoot}: ${manifestLines.length + 1} files, ${bytes} bytes`);
