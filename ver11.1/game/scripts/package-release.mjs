import { createHash } from "node:crypto";
import { cp, mkdir, readFile, readdir, rm, stat, writeFile } from "node:fs/promises";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const gameRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const distRoot = resolve(gameRoot, "dist");
const releaseRoot = resolve(gameRoot, "..", "release", "gale-thread-v11.1");

const guide = `GALE THREAD v11.1

Serve this directory with a static web server and open it in Google Chrome.

Controls
- Enter: launch or continue
- Left / Right on the title: choose any unlocked airspace
- Left / Right or A / D: steer
- Hold Space: reel in and climb
- Release Space: pay out thread and descend
- Escape: pause or resume
- S: open settings
- R: retry the current airspace

Progress, sound volume, and reduced-motion preference are stored in the browser. Visuals and sounds are generated by the game code; no third-party media is included.
`;

async function listFiles(directory) {
  const files = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = resolve(directory, entry.name);
    if (entry.isDirectory()) files.push(...await listFiles(path));
    else files.push(path);
  }
  return files;
}

await readFile(resolve(distRoot, "index.html"), "utf8");
await rm(releaseRoot, { recursive: true, force: true });
await mkdir(releaseRoot, { recursive: true });
await cp(distRoot, releaseRoot, { recursive: true });
await writeFile(resolve(releaseRoot, "README.txt"), guide, "utf8");

const checksums = [];
for (const path of (await listFiles(releaseRoot)).sort()) {
  const digest = createHash("sha256").update(await readFile(path)).digest("hex");
  checksums.push(`${digest}  ${relative(releaseRoot, path)}`);
}
await writeFile(resolve(releaseRoot, "SHA256SUMS.txt"), `${checksums.join("\n")}\n`, "utf8");

const bytes = (await Promise.all((await listFiles(releaseRoot)).map(async (path) => (await stat(path)).size)))
  .reduce((total, size) => total + size, 0);
console.log(`Packaged ${releaseRoot}: ${checksums.length + 1} files, ${bytes} bytes`);
